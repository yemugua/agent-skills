def norm(s):
    return (s or '').replace(' ', '').replace('\u3000', '')


def analyse(text):
    t = norm(text)
    nature = []
    for n in NATURE:
        hits = [k for k in n['kw'] if k in t]
        if hits:
            nature.append({'id': n['id'], 'name': n['name'], 'level': n['level'],
                           'hits': hits, 'test': n['test'], 'msg': n['msg']})
    depth = []
    for p in DEPTH:
        hits = [k for k in p['kw'] if k in t]
        if hits:
            depth.append({'id': p['id'], 'name': p['name'], 'level': p['level'],
                          'hits': hits, 'msg': p['msg']})
    spots = []
    for s in SPOT:
        hits = [k for k in s['kw'] if k in t]
        if hits:
            spots.append({'id': s['id'], 'name': s['name'], 'hits': hits,
                          'src': s['src'], 'first': s['first']})
    reds = [r['msg'] for r in RED if any(k in t for k in r['kw'])]
    miss = [m['msg'] for m in MISREAD if any(k in t for k in m['kw'])]
    deep = any(p['id'] == 'P1' for p in depth)
    area = any(k in t for k in ['\u5927\u9762\u79ef', '\u6574\u9762\u5899', '\u4e00\u6574\u9762', '\u4e00\u9762\u5899', '\u5f88\u591a\u623f\u95f4', '\u5168\u5c4b'])
    must_pro = deep or area or len(reds) > 0
    return {'nature': nature, 'depth': depth, 'spots': spots, 'reds': reds,
            'misread': miss, 'steps': FOUR_STEPS, 'must_pro': must_pro,
            'top': nature[0]['name'] if nature else '',
            'top_spot': spots[0]['name'] if spots else ''}


