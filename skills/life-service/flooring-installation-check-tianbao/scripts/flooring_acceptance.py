def main():
    ap = argparse.ArgumentParser(description='\u5730\u677f\u94fa\u88c5\u9a8c\u6536\u6838\u67e5\u6e05\u5355')
    ap.add_argument('--check', help='\u9a8c\u6536\u9879\uff0c\u9017\u53f7\u5206\u9694\uff0c\u6216\u586b \u5168\u90e8')
    ap.add_argument('--file', help='\u4ece\u6587\u4ef6\u8bfb\uff0c\u652f\u6301 txt / md / json')
    ap.add_argument('--out', help='\u7ed3\u679c\u8f93\u51fa\u8def\u5f84')
    ap.add_argument('--format', default='md', choices=['md', 'json'])
    ap.add_argument('--selftest', action='store_true')
    a = ap.parse_args()

    if a.selftest:
        return selftest()

    spec = a.check or ''
    if a.file:
        if not os.path.exists(a.file):
            print('ERROR --file \u4e0d\u5b58\u5728')
            return 2
        spec = read_input(a.file)
    if not spec.strip():
        spec = '\u5168\u90e8'

    r = analyse(spec)
    out = render_md(r) if a.format == 'md' else json.dumps(r, ensure_ascii=False, indent=2)
    if a.out:
        with open(a.out, 'w', encoding='utf-8') as f:
            f.write(out + '\n')
        print('\u6e05\u5355\u5df2\u5199\u5165: %s' % a.out)
    print(out)
    return 0


